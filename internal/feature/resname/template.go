package resname

import (
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
)

var (
	errorsNew           = protogen.GoImportPath("errors").Ident("New")
	fmtErrorf           = protogen.GoImportPath("fmt").Ident("Errorf")
	stringsSplit        = protogen.GoImportPath("strings").Ident("Split")
	stringsContainsRune = protogen.GoImportPath("strings").Ident("ContainsRune")
	utf8ValidString     = protogen.GoImportPath("unicode/utf8").Ident("ValidString")
)

const (
	sentinel      = "ErrInvalidResourceName"
	segmentHelper = "resnameSegment"
	strictHelper  = "resnameStrictSegment"
)

// emit writes the whole output file for one input file from its model.
func emit(g *protogen.GeneratedFile, f *protogen.File, fm *fileModel, cfg Config, version string) {
	g.P("// Code generated by protoc-gen-resname ", version, ". DO NOT EDIT.")
	g.P("// source: ", f.Desc.Path())
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	if fm.Helpers {
		emitHelpers(g, cfg)
	}
	for _, r := range fm.Resources {
		emitResource(g, r, cfg)
	}
	for _, ref := range fm.Refs {
		emitReference(g, ref)
	}
}

// emitHelpers writes the per-package sentinel and the segment validator.
func emitHelpers(g *protogen.GeneratedFile, cfg Config) {
	g.P("// ", sentinel, " is wrapped by every resource-name parse and validation error")
	g.P("// in this package; test for it with errors.Is.")
	g.P("var ", sentinel, " = ", errorsNew, `("invalid resource name")`)
	g.P()
	g.P("// ", segmentHelper, " validates one segment of a resource name: it must be non-empty,")
	if cfg.StrictSegments {
		g.P("// match [a-z0-9-]{1,63}, and be the wildcard \"-\" only when allowWildcard is set.")
	} else {
		g.P("// contain no slash, be valid UTF-8, and be the wildcard \"-\" only when")
		g.P("// allowWildcard is set.")
	}
	g.P("func ", segmentHelper, "(kind, name, variable, value string, allowWildcard bool) error {")
	g.P("switch {")
	g.P("case value == \"\":")
	g.P("return ", fmtErrorf, `("%w: %s name %q: segment {%s} is empty", `, sentinel, ", kind, name, variable)")
	g.P("case value == \"-\":")
	g.P("if allowWildcard {")
	g.P("return nil")
	g.P("}")
	g.P("return ", fmtErrorf, `("%w: %s name %q: segment {%s} must not be a wildcard", `, sentinel, ", kind, name, variable)")
	if cfg.StrictSegments {
		g.P("case !", strictHelper, "(value):")
		g.P("return ", fmtErrorf, `("%w: %s name %q: segment {%s} must match [a-z0-9-]{1,63}", `, sentinel, ", kind, name, variable)")
	} else {
		g.P("case ", stringsContainsRune, "(value, '/'):")
		g.P("return ", fmtErrorf, `("%w: %s name %q: segment {%s} must not contain a slash", `, sentinel, ", kind, name, variable)")
		g.P("case !", utf8ValidString, "(value):")
		g.P("return ", fmtErrorf, `("%w: %s name %q: segment {%s} is not valid UTF-8", `, sentinel, ", kind, name, variable)")
	}
	g.P("}")
	g.P("return nil")
	g.P("}")
	g.P()
	if cfg.StrictSegments {
		g.P("// ", strictHelper, " reports whether value matches [a-z0-9-]{1,63}.")
		g.P("func ", strictHelper, "(value string) bool {")
		g.P("if len(value) == 0 || len(value) > 63 {")
		g.P("return false")
		g.P("}")
		g.P("for i := 0; i < len(value); i++ {")
		g.P("c := value[i]")
		g.P("if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-') {")
		g.P("return false")
		g.P("}")
		g.P("}")
		g.P("return true")
		g.P("}")
		g.P()
	}
}

// emitResource writes the constants, the name type(s), their methods and
// the message accessors of one resource.
func emitResource(g *protogen.GeneratedFile, r *Resource, cfg Config) {
	kind := r.Kind
	g.P("// ", kind, "Type is the resource type of ", r.Type, ".")
	g.P("const ", kind, "Type = ", strconv.Quote(r.Type))
	g.P()
	if r.Multi {
		g.P("// ", kind, "NamePattern is the canonical (first) resource-name pattern of ", r.Type, ".")
	} else {
		g.P("// ", kind, "NamePattern is the resource-name pattern of ", r.Type, ".")
	}
	g.P("const ", kind, "NamePattern = ", strconv.Quote(r.Patterns[0].Raw))
	g.P()
	if r.Multi {
		for _, v := range r.Variants {
			g.P("// ", v.Ident.GoName, "Pattern is the resource-name pattern parsed by Parse", v.Ident.GoName, ".")
			g.P("const ", v.Ident.GoName, "Pattern = ", strconv.Quote(v.Pattern.Raw))
			g.P()
		}
		emitInterface(g, r, cfg)
	}
	if len(r.Parents) > 1 {
		emitParentInterface(g, r)
	}
	for _, v := range r.Variants {
		emitVariant(g, v, cfg)
	}
	if r.Message != nil {
		recv := r.Message.GoIdent
		g.P("// ResourceName parses the ", r.NameField, " field of x as a ", r.Type, " resource name.")
		g.P("func (x *", recv, ") ResourceName() (", r.NameIdent, ", error) {")
		g.P("return Parse", r.NameIdent.GoName, "(x.Get", r.nameFieldGoName, "())")
		g.P("}")
		g.P()
		g.P("// MustResourceName is ResourceName that panics on error.")
		g.P("func (x *", recv, ") MustResourceName() ", r.NameIdent, " {")
		g.P("n, err := x.ResourceName()")
		g.P("if err != nil {")
		g.P("panic(err)")
		g.P("}")
		g.P("return n")
		g.P("}")
		g.P()
	}
}

// emitInterface writes the interface and dispatching parser of a
// multi-pattern resource (spec §4.5).
func emitInterface(g *protogen.GeneratedFile, r *Resource, cfg Config) {
	name := r.NameIdent.GoName
	var variants []string
	for _, v := range r.Variants {
		variants = append(variants, v.Ident.GoName)
	}
	g.P("// ", name, " is the parsed resource name of a ", r.Type, "; it is one of")
	g.P("// ", strings.Join(variants, ", "), ".")
	g.P("type ", name, " interface {")
	g.P("String() string")
	g.P("MarshalString() (string, error)")
	g.P("Validate() error")
	g.P("ValidateAllowWildcard() error")
	g.P("ContainsWildcard() bool")
	g.P("Type() string")
	g.P("is", name, "()")
	g.P("}")
	g.P()
	g.P("// Parse", name, " parses name against each pattern of ", r.Type, " in declaration order")
	g.P("// and returns the first match.", wildcardNote(cfg))
	g.P("func Parse", name, "(name string) (", name, ", error) {")
	for _, v := range r.Variants {
		g.P("if n, err := Parse", v.Ident.GoName, "(name); err == nil {")
		g.P("return n, nil")
		g.P("}")
	}
	g.P("return nil, ", fmtErrorf, `("%w: `, r.Display, ` name %q: matches no pattern of `, r.Type, `", `, sentinel, ", name)")
	g.P("}")
	g.P()
	emitMust(g, name, name)
}

// emitParentInterface writes the interface over the possible parents of a
// resource with several known parents, used by child_type accessors.
func emitParentInterface(g *protogen.GeneratedFile, r *Resource) {
	name := r.ParentIdent.GoName
	var parents []string
	for _, p := range r.Parents {
		parents = append(parents, g.QualifiedGoIdent(p.Ident))
	}
	g.P("// ", name, " is the resource name of a parent of a ", r.Type, "; it is one of")
	g.P("// ", strings.Join(parents, ", "), ".")
	g.P("type ", name, " interface {")
	g.P("String() string")
	g.P("MarshalString() (string, error)")
	g.P("Validate() error")
	g.P("ValidateAllowWildcard() error")
	g.P("ContainsWildcard() bool")
	g.P("Type() string")
	g.P("}")
	g.P()
	g.P("// Parse", name, " parses name as the parent of a ", r.Type, ", trying each parent")
	g.P("// pattern in the order of the child's patterns.")
	g.P("func Parse", name, "(name string) (", name, ", error) {")
	for _, p := range r.Parents {
		g.P("if n, err := ", p.ParseIdent(), "(name); err == nil {")
		g.P("return n, nil")
		g.P("}")
	}
	g.P("return nil, ", fmtErrorf, `("%w: `, r.Display, ` parent name %q: matches no parent pattern of `, r.Type, `", `, sentinel, ", name)")
	g.P("}")
	g.P()
	emitMust(g, name, name)
}

func emitMust(g *protogen.GeneratedFile, name, ret string) {
	g.P("// MustParse", name, " is Parse", name, " that panics on error.")
	g.P("func MustParse", name, "(name string) ", ret, " {")
	g.P("n, err := Parse", name, "(name)")
	g.P("if err != nil {")
	g.P("panic(err)")
	g.P("}")
	g.P("return n")
	g.P("}")
	g.P()
}

func wildcardNote(cfg Config) string {
	if cfg.Wildcards {
		return ` Wildcard "-" segments are accepted.`
	}
	return ` Wildcard "-" segments are rejected.`
}

// emitVariant writes one concrete name struct with its parser and methods
// (spec §4.4).
func emitVariant(g *protogen.GeneratedFile, v *Variant, cfg Config) {
	r := v.Resource
	name := v.Ident.GoName
	p := v.Pattern
	display := strconv.Quote(r.Display)
	wild := strconv.FormatBool(cfg.Wildcards)

	g.P("// ", name, " is the parsed resource name of a ", r.Type, ":")
	g.P("// ", p.Raw, ".")
	g.P("type ", name, " struct {")
	for _, fld := range v.Fields {
		g.P(fld.GoName, " string")
	}
	g.P("}")
	g.P()

	g.P("// Parse", name, " parses name against ", name, "Pattern.", wildcardNote(cfg))
	g.P("func Parse", name, "(name string) (", name, ", error) {")
	g.P("segments := ", stringsSplit, "(name, \"/\")")
	g.P("if len(segments) != ", len(p.Segments), " {")
	g.P("return ", name, "{}, ", fmtErrorf, `("%w: `, r.Display, ` name %q: expected `, len(p.Segments), ` segments, got %d", `, sentinel, ", name, len(segments))")
	g.P("}")
	for i, seg := range p.Segments {
		if seg.IsVariable() {
			g.P("if err := ", segmentHelper, "(", display, ", name, ", strconv.Quote(seg.Variable), ", segments[", i, "], ", wild, "); err != nil {")
			g.P("return ", name, "{}, err")
			g.P("}")
			continue
		}
		g.P("if segments[", i, "] != ", strconv.Quote(seg.Literal), " {")
		g.P("return ", name, "{}, ", fmtErrorf, `("%w: `, r.Display, ` name %q: expected %q at segment `, i+1, `, got %q", `, sentinel, ", name, ", strconv.Quote(seg.Literal), ", segments[", i, "])")
		g.P("}")
	}
	var init []string
	for i, seg := range p.Segments {
		if seg.IsVariable() {
			init = append(init, v.Field(seg.Variable).GoName+": segments["+strconv.Itoa(i)+"]")
		}
	}
	g.P("return ", name, "{", strings.Join(init, ", "), "}, nil")
	g.P("}")
	g.P()
	emitMust(g, name, name)

	g.P("// String formats the name without validating it.")
	g.P("func (n ", name, ") String() string {")
	var parts []string
	for _, seg := range p.Segments {
		if seg.IsVariable() {
			parts = append(parts, "n."+v.Field(seg.Variable).GoName)
		} else {
			parts = append(parts, strconv.Quote(seg.Literal))
		}
	}
	g.P("return ", joinConcat(parts))
	g.P("}")
	g.P()

	g.P("// MarshalString validates the name, then formats it.")
	g.P("func (n ", name, ") MarshalString() (string, error) {")
	g.P("if err := n.Validate(); err != nil {")
	g.P("return \"\", err")
	g.P("}")
	g.P("return n.String(), nil")
	g.P("}")
	g.P()

	g.P("// UnmarshalString parses s into n.")
	g.P("func (n *", name, ") UnmarshalString(s string) error {")
	g.P("parsed, err := Parse", name, "(s)")
	g.P("if err != nil {")
	g.P("return err")
	g.P("}")
	g.P("*n = parsed")
	g.P("return nil")
	g.P("}")
	g.P()

	g.P("// Validate checks that every segment is set and well-formed; the wildcard \"-\"")
	g.P("// is rejected.")
	g.P("func (n ", name, ") Validate() error {")
	g.P("return n.validate(false)")
	g.P("}")
	g.P()
	g.P("// ValidateAllowWildcard is Validate with the wildcard \"-\" accepted in any segment.")
	g.P("func (n ", name, ") ValidateAllowWildcard() error {")
	g.P("return n.validate(true)")
	g.P("}")
	g.P()
	g.P("func (n ", name, ") validate(allowWildcard bool) error {")
	g.P("name := n.String()")
	for _, fld := range v.Fields {
		g.P("if err := ", segmentHelper, "(", display, ", name, ", strconv.Quote(fld.Variable), ", n.", fld.GoName, ", allowWildcard); err != nil {")
		g.P("return err")
		g.P("}")
	}
	g.P("return nil")
	g.P("}")
	g.P()

	g.P("// ContainsWildcard reports whether any segment is the wildcard \"-\".")
	g.P("func (n ", name, ") ContainsWildcard() bool {")
	var checks []string
	for _, fld := range v.Fields {
		checks = append(checks, "n."+fld.GoName+` == "-"`)
	}
	g.P("return ", strings.Join(checks, " || "))
	g.P("}")
	g.P()

	g.P("// Type returns ", r.Kind, "Type.")
	g.P("func (n ", name, ") Type() string {")
	g.P("return ", r.Kind, "Type")
	g.P("}")
	g.P()

	if v.Parent != nil {
		pr := v.Parent
		g.P("// Parent returns the name of the parent ", pr.Resource.Type, ".")
		g.P("func (n ", name, ") Parent() ", pr.Ident, " {")
		var init []string
		for _, fld := range pr.Fields {
			init = append(init, fld.GoName+": n."+v.Field(fld.Variable).GoName)
		}
		g.P("return ", pr.Ident, "{", strings.Join(init, ", "), "}")
		g.P("}")
		g.P()
	}

	g.P("// IsZero reports whether every segment is empty.")
	g.P("func (n ", name, ") IsZero() bool {")
	g.P("return n == ", name, "{}")
	g.P("}")
	g.P()

	if r.Multi {
		g.P("func (", name, ") is", r.NameIdent.GoName, "() {}")
		g.P()
	}
}

// emitReference writes one resource_reference accessor (spec §4.6).
func emitReference(g *protogen.GeneratedFile, ref *Reference) {
	recv := ref.Message.GoIdent
	fieldName := string(ref.Field.Desc.Name())
	getter := "x.Get" + ref.Field.GoName + "()"
	if !ref.Repeated {
		g.P("// ", ref.Method, " parses the ", fieldName, " field of x as a ", g.QualifiedGoIdent(ref.Return), ".")
		g.P("func (x *", recv, ") ", ref.Method, "() (", ref.Return, ", error) {")
		g.P("return ", ref.Parse, "(", getter, ")")
		g.P("}")
		g.P()
		return
	}
	g.P("// ", ref.Method, " parses every element of the ", fieldName, " field of x as a ", g.QualifiedGoIdent(ref.Return), ".")
	g.P("func (x *", recv, ") ", ref.Method, "() ([]", ref.Return, ", error) {")
	g.P("values := ", getter)
	g.P("names := make([]", ref.Return, ", 0, len(values))")
	g.P("for i, value := range values {")
	g.P("n, err := ", ref.Parse, "(value)")
	g.P("if err != nil {")
	g.P("return nil, ", fmtErrorf, "(\"", fieldName, "[%d]: %w\", i, err)")
	g.P("}")
	g.P("names = append(names, n)")
	g.P("}")
	g.P("return names, nil")
	g.P("}")
	g.P()
}

// joinConcat renders a Go string concatenation, merging adjacent literals
// with their separating slashes: "publishers/" + n.Publisher + "/books/" + n.Book.
func joinConcat(parts []string) string {
	var out []string
	lit := ""
	flush := func() {
		if lit != "" {
			out = append(out, strconv.Quote(lit))
			lit = ""
		}
	}
	for i, p := range parts {
		if i > 0 {
			lit += "/"
		}
		if strings.HasPrefix(p, `"`) {
			s, _ := strconv.Unquote(p)
			lit += s
			continue
		}
		flush()
		out = append(out, p)
	}
	flush()
	return strings.Join(out, " + ")
}
